import { fetchDatasetOverview, type DatasetOverview } from '@/lib/datapool-of-dataset'
import { readAllInstallations } from '@/lib/installation-list'
import { fetchInstalledDashboards, type InstalledDashboardLink } from '@/lib/installed-dashboards'
import type { ActiveInstallation } from '@/lib/installations'
import { getAccessToken } from '@/lib/session'
import { isSimulatorConfigured, listSimulations } from '@/lib/simulator/client'
import { streamsOfInstallation, type InstallationStream } from '@/lib/simulator/registration'

/**
 * Everything the "In dieser Instanz" card shows for ONE installation, found by
 * the installation's id rather than by a catalogue entry. That makes it work
 * for every active installation, including the ones the assistant generated,
 * which are in no catalogue: their package id is unknown there, so they simply
 * show no dashboards.
 */

interface InstallationRow {
    id: string
    packageId?: string
    packageVersion?: string
    uninstalledAt?: string | null
    dataSetId?: string
    dataSetName?: string
    artifacts?: { artifactType?: string }[]
}

export interface InstallationView {
    installation: ActiveInstallation
    title: string
    packageId?: string
    packageVersion?: string
    /** Generated by the assistant (its packages carry their own id prefix, see lib/assistant/usecase). */
    generated: boolean
    dataset: DatasetOverview | null
    dashboards: InstalledDashboardLink[]
    streams: InstalledStreams
}

/** Null: simulator not configured or not reachable. Empty: reachable, no streams for this installation. */
type InstalledStreams = InstallationStream[] | null

async function readInstallationStreams(installationId: string): Promise<InstalledStreams> {
    if (!isSimulatorConfigured()) return null
    try {
        return streamsOfInstallation(await listSimulations(), installationId)
    } catch {
        return null
    }
}

/** Null when the installation is unknown, uninstalled, or the record cannot be read. */
export async function loadInstallationView(installationId: string): Promise<InstallationView | null> {
    const accessToken = await getAccessToken()
    const list = await readAllInstallations<InstallationRow>(accessToken)
    if (!list.ok) return null
    const row = list.rows.find((candidate) => candidate.id === installationId && !candidate.uninstalledAt)
    if (!row) return null

    const installation: ActiveInstallation = {
        id: row.id,
        ...(row.dataSetId ? { dataSetId: row.dataSetId } : {}),
        ...(row.dataSetName ? { dataSetName: row.dataSetName } : {}),
        hasDataSource: (row.artifacts ?? []).some((artifact) => artifact.artifactType === 'DATA_SOURCE'),
    }
    const [dataset, dashboards, streams] = await Promise.all([
        row.dataSetId ? fetchDatasetOverview(row.dataSetId, accessToken) : Promise.resolve(null),
        row.packageId ? fetchInstalledDashboards(row.packageId, row.id) : Promise.resolve([]),
        readInstallationStreams(row.id),
    ])

    return {
        installation,
        title: row.dataSetName ?? row.packageId ?? row.id,
        ...(row.packageId ? { packageId: row.packageId } : {}),
        ...(row.packageVersion ? { packageVersion: row.packageVersion } : {}),
        generated: Boolean(row.packageId?.startsWith('urn:openurbanapps:usecase:assistent-')),
        dataset,
        dashboards,
        streams,
    }
}
